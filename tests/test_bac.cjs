const assert=require('node:assert/strict');const m=require('../app/static/bac-model.js');
const p={massKg:80,distribution:.68,eliminationPercentPerHour:.015,hours:8,drinks:[{timeHours:0,ethanolG:14,absorptionPerHour:3}]};
assert.equal(m.bacAt(0,p),0);
assert.ok(Math.abs(m.bacAt(1,p)-(.1*14/(80*.68)*(1-Math.exp(-3))-.015))<1e-12);
assert.equal(m.bacAt(8,p),0);
assert.equal(m.bacAt(1,{...p,drinks:[{...p.drinks[0],timeHours:2}]}),0);
const two={...p,drinks:[...p.drinks,{timeHours:2,ethanolG:14,absorptionPerHour:2.2}]};
assert.equal(m.bacAt(2,two),m.bacAt(2,p));assert.ok(m.bacAt(3,two)>m.bacAt(3,p));
const noDecay={...p,eliminationPercentPerHour:0};assert.ok(Math.abs(m.bacAt(8,noDecay)-.1*14/(80*.68))<1e-10);
assert.equal(m.ethanolFromVolume(500,5),19.725);
assert.equal(m.series(p).length,481);assert.equal(m.series(p).at(-1).timeHours,8);
assert.throws(()=>m.series({...p,massKg:0}));assert.throws(()=>m.series({...p,drinks:[]}));assert.throws(()=>m.series({...p,drinks:[{...p.drinks[0],absorptionPerHour:0}]}));assert.throws(()=>m.series({...p,drinks:[{...p.drinks[0],timeHours:9}]}));assert.throws(()=>m.ethanolFromVolume(500,101));
console.log('BAC model: unit conversion, absorption, elimination, superposition, time range and validation checks passed');
